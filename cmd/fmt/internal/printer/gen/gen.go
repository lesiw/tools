// Command gen copies go/printer into the parent directory from the
// toolchain matching the module's go directive and applies
// printer.patch, so the vendored copy is reproducible from upstream
// rather than hand-maintained.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const header = "// Code generated by internal/printer/gen. DO NOT EDIT.\n\n"

var files = []string{"printer.go", "nodes.go", "comment.go", "gobuild.go"}

func main() {
	src, err := printerDir()
	if err != nil {
		fatal(err)
	}
	for _, name := range files {
		b, err := os.ReadFile(filepath.Join(src, name))
		if err != nil {
			fatal(err)
		}
		if err := os.WriteFile(name, b, 0o644); err != nil {
			fatal(err)
		}
	}
	patch := filepath.Join("gen", "printer.patch")
	apply := exec.Command("git", "apply", patch)
	apply.Stderr = os.Stderr
	if err := apply.Run(); err != nil {
		fatal(fmt.Errorf("git apply: %w", err))
	}
	for _, name := range files {
		b, err := os.ReadFile(name)
		if err != nil {
			fatal(err)
		}
		text := append([]byte(header), b...)
		if err := os.WriteFile(name, text, 0o644); err != nil {
			fatal(err)
		}
	}
}

// printerDir locates go/printer's source in the running toolchain
// after confirming its language version matches the module's go
// directive, so the copy can never come from a newer Go than the
// module supports.
func printerDir() (string, error) {
	out, err := exec.Command("go", "mod", "edit", "-json").Output()
	if err != nil {
		return "", err
	}
	var mod struct{ Go string }
	if err := json.Unmarshal(out, &mod); err != nil {
		return "", err
	}
	env, err := exec.Command(
		"go", "env", "-json", "GOROOT", "GOVERSION",
	).Output()
	if err != nil {
		return "", err
	}
	var tc struct{ GOROOT, GOVERSION string }
	if err := json.Unmarshal(env, &tc); err != nil {
		return "", err
	}
	want := minor(mod.Go)
	have := minor(strings.TrimPrefix(tc.GOVERSION, "go"))
	if want != have {
		return "", fmt.Errorf(
			"toolchain is go%s but go.mod declares go %s: "+
				"rerun with a go%s toolchain", have, mod.Go, want,
		)
	}
	return filepath.Join(tc.GOROOT, "src", "go", "printer"), nil
}

// minor truncates a Go version to its language version.
func minor(v string) string {
	if i := strings.LastIndex(v, "."); strings.Count(v, ".") == 2 {
		return v[:i]
	}
	return v
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func TestGather(t *testing.T) {
	var (
		dir   = t.TempDir()
		files = []string{"a.go", "b_test.go", ".c.go", "d.txt"}
	)
	for _, name := range files {
		writeFile(t, filepath.Join(dir, name), "package p\n")
	}
	if err := os.MkdirAll(filepath.Join(dir, ".git"), 0o755); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(dir, ".git", "e.go"), "package p\n")
	got, err := gather([]string{dir})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		filepath.Join(dir, ".git", "e.go"),
		filepath.Join(dir, "a.go"),
		filepath.Join(dir, "b_test.go"),
	}
	if !slices.Equal(got, want) {
		t.Errorf("gather = %q, want %q", got, want)
	}
}

func TestFormatFile(t *testing.T) {
	var (
		dir   = t.TempDir()
		clean = filepath.Join(dir, "clean.go")
		raw   = filepath.Join(dir, "raw.go")
	)
	writeFile(t, clean, "package p\n")
	writeFile(t, raw, "package p\nfunc  f () {}\n")
	*list, *write = false, false
	if out := stdout(t, clean); out != "package p\n" {
		t.Errorf("stdout = %q, want the formatted file", out)
	}
	*list = true
	if name, _, err := formatFile(clean); err != nil || name != "" {
		t.Errorf("-l listed a formatted file: %q, %v", name, err)
	}
	if name, _, err := formatFile(raw); err != nil || name != raw {
		t.Errorf("-l = %q, %v, want %q", name, err, raw)
	}
	*write = true
	if _, _, err := formatFile(raw); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(raw)
	if err != nil {
		t.Fatal(err)
	}
	if want := "package p\n\nfunc f() {}\n"; string(got) != want {
		t.Errorf("after -w the file is %q, want %q", got, want)
	}
}

// TestListAndWrite holds -l -w to gofmt's: the file is named and rewritten.

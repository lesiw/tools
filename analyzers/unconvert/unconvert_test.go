//go:embed testdata
var testdata embed.FS

func TestAnalysisTest(t *testing.T) {
	dir := fixtures.Dir(t, testdata)
	analysistest.RunWithSuggestedFixes(t, dir, Analyzer, "a")
}

func TestGeneratedNames(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want bool
	}{{
		name: "dir/_cgo_gotypes.go",
		src:  "package a\n",
		want: true,
	}, {
		name: "dir/_cgo_import.go",
		src:  "package a\n",
		want: true,
	}, {
		name: "dir/0123456789abcdef-d",
		src:  "package a\n",
		want: true,
	}, {
		name: "dir/item.cgo1.go",
		src:  "package a\n",
		want: true,
	}, {
		name: "dir/generated.go",
		src:  "// Code generated by a tool; DO NOT EDIT.\n\npackage a\n",
		want: true,
	}, {
		name: "dir/item.go",
		src:  "package a\n",
		want: false,
	}}
	for _, test := range tests {
		fset := token.NewFileSet()
		file, err := parser.ParseFile(
			fset, test.name, test.src,
			parser.ParseComments,
		)
		if err != nil {
			t.Fatal(err)
		}
		pass := &analysis.Pass{Fset: fset}
		if got := generated(pass, file); got != test.want {
			t.Errorf("%s: generated is %v, want %v", test.name, got, test.want)
		}
	}
}
